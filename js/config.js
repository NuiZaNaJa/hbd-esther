/* ------------------------------------------------------------
   นับวันถึงวันเกิด (เวอร์ชันถัดไปถ้าวันนี้ผ่านไปแล้ว)
   คืนค่า: { days: จำนวนวัน, isToday: true/false }
   ------------------------------------------------------------ */
function daysUntilBirthday() {
  const now = new Date();
  const isToday =
    now.getDate() === CONFIG.birthday.day &&
    now.getMonth() + 1 === CONFIG.birthday.month;

  const todayStart = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  let target = new Date(now.getFullYear(), CONFIG.birthday.month - 1, CONFIG.birthday.day);
  if (!isToday && target < todayStart) {
    target = new Date(now.getFullYear() + 1, CONFIG.birthday.month - 1, CONFIG.birthday.day);
  }
  const days = Math.round((target - todayStart) / 86400000);
  return { days: isToday ? 0 : days, isToday };
}
